// 長いキーワードを優先（例: 武蔵小杉 が 小杉/杉 より先）
const KW_KEYS = Object.keys(KW).sort((a, b) => b.length - a.length);

// 店舗名 → prefRank。"NAORU " や "院" を除いた地名部分でキーワード一致を探す。未判定は950。
export function shopGeoRank(name) {
  const s = String(name || '').replace(/NAORU/gi, '').replace(/院/g, '').trim();
  for (const k of KW_KEYS) { if (s.includes(k)) return KW[k]; }
  return 950; // 国内その他（海外の直前）
}

// 並び替え比較（rank昇順→名前）。組織図で shops.sort(compareShopsByGeo) に使う。
export function compareShopsByGeo(a, b) {
  const ra = shopGeoRank(a && a.name), rb = shopGeoRank(b && b.name);
  if (ra !== rb) return ra - rb;
  return String((a && a.name) || '').localeCompare(String((b && b.name) || ''), 'ja');
}

// 店舗配列を地域グループ（北→南→その他→海外）に分けて返す。
// [{ rank(region代表), region, shops:[...] }]
export function groupShopsByRegion(shops) {
  const buckets = new Map(); // regionRank(代表) → { region, shops }
  const regionRepRank = { '北海道': 1, '東北': 2, '関東': 8, '中部': 15, '近畿': 24, '中国': 31, '四国': 36, '九州': 40, '沖縄': 47, 'その他': 950, '海外': 1000 };
  for (const sh of (Array.isArray(shops) ? shops : [])) {
    const region = regionOf(shopGeoRank(sh && sh.name));
    if (!buckets.has(region)) buckets.set(region, []);
    buckets.get(region).push(sh);
  }
  return [...buckets.entries()]
    .map(([region, list]) => ({ region, rank: regionRepRank[region] ?? 900, shops: list.slice().sort(compareShopsByGeo) }))
    .sort((a, b) => a.rank - b.rank);
}
