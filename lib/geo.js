// prefRank: 1=北海道 … 47=沖縄（地理的に北→南）。海外=1000、判定不能(国内その他)=950（海外の直前）。

// 地域名（見出し用）を prefRank から返す
export function regionOf(rank) {
  if (rank === 1) return '北海道';
  if (rank >= 2 && rank <= 7) return '東北';
  if (rank >= 8 && rank <= 14) return '関東';
  if (rank >= 15 && rank <= 23) return '中部';
  if (rank >= 24 && rank <= 30) return '近畿';
  if (rank >= 31 && rank <= 35) return '中国';
  if (rank >= 36 && rank <= 39) return '四国';
  if (rank >= 40 && rank <= 46) return '九州';
  if (rank === 47) return '沖縄';
  if (rank >= 1000) return '海外';
  return 'その他';
}

